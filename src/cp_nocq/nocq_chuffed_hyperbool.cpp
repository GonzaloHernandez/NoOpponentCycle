class NOCCheckerSCC : public Propagator {
private:
    Game& g;
    vec<BoolView> V;
    parity_type playerSAT;
    WinningCondition*  winCondition;

public:
    //-------------------------------------------------------------------------
    NOCCheckerSCC(Game& g, vec<BoolView>& V,
        parity_type playerSAT, WinningCondition* winCondition) 
    : g(g), V(V), playerSAT(playerSAT), winCondition(winCondition)
    {
        for (unsigned int i = 0; i < g.nvertices; i++)  
            V[i].attach(this, 1, EVENT_F);
    }

    //-------------------------------------------------------------------------
    bool backtrack() 
    {
        vec<Lit> lits;
        lits.push(); // First slot reserved for explanation placeholder
        for (unsigned int i = 1; i < g.nvertices; i++)   lits.push(V[i].getValLit());
        Clause* reason = Reason_new(lits);
        V[0].setVal(!V[0].isTrue(), reason);
        return false;
    }

    //-------------------------------------------------------------------------
    bool check(GameView& view) {
        // Line 1: Tarjan(G)
        TarjanSCC tarjan(g, view);
        vec<vec<int32_t>*> sccs;
        tarjan.solve(sccs);

        bool status = true;

        for (int i = 0; i < sccs.size(); i++) {
            vec<int32_t>& scc = *sccs[i];
            vec<int32_t> objectiveSet;

            // Compute objectiveSet = { v in scc | f_player(scc) holds true }
            winCondition->satisfySCC(scc, objectiveSet);

            // Line 2: IF |scc| == 1
            if (scc.size() == 1) {
                int32_t v = scc[0];

                // Line 4: Check if E_[vEv] holds (Active self loop)
                bool has_active_self_loop = false;
                vec<int32_t> outEdges;
                view.getOuts(outEdges, v);
                for (int j = 0; j < outEdges.size(); j++) {
                    if (g.targets[outEdges[j]] == v) {
                        has_active_self_loop = true;
                        break;
                    }
                }

                // If active self-loop and objectiveSet is empty -> Win Opponent Cycle Found
                if (has_active_self_loop && objectiveSet.size() == 0) {
                    status = false; 
                    break;
                }
            } 
            // Line 8: ELSE (|scc| > 1)
            else {
                // Line 11: IF objectiveSet == empty -> Win Opponent Cycle Found
                if (objectiveSet.size() == 0) {
                    status = false; 
                    break;
                }

                // Line 16: Recursive invocation on G \ objectiveSet
                // Mask out elements in objectiveSet from our GameView
                for (int j = 0; j < objectiveSet.size(); j++) {
                    view.vs[objectiveSet[j]] = false;
                }

                // Deep recursion
                bool subResult = check(view);

                // Backtrack mask to restore view state for peer SCC loops
                for (int j = 0; j < objectiveSet.size(); j++) {
                    view.vs[objectiveSet[j]] = true;
                }

                if (!subResult) {
                    status = false;
                    break;
                }
            }
        }

        // Deallocate memory generated by Tarjan's solver
        for (int i = 0; i < sccs.size(); i++) {
            delete sccs[i];
        }

        return status;
    }

    //-------------------------------------------------------------------------
    bool propagate() override {
        GameView view(g);
        view.deactiveAll();

        for (unsigned int i = 0; i < g.nvertices; i++) {
            if (!V[i].isFixed()) return true;
            if (V[i].isTrue()) view.vs[i] = true;
        }

        if (!check(view)) {
            return backtrack();
        }

        return true;
    }

    //-------------------------------------------------------------------------
    void wakeup(int i, int) override {
        pushInQueue();
    }

    //-------------------------------------------------------------------------
    void clearPropState() override {
        in_queue = false;
    }
};

